// 4. Dictionary entries (25 Paris lessons + master + functional + trail) are
//    registered LAST, as a gap-fill: they only add words not already present
//    in the CEFR bank. This keeps the curated CEFR level as the source of
//    truth, instead of letting placeholder `difficultyLevel: "undefined"`
//    entries lock common words at A1.
for (const key of Object.keys(LESSON_DICTIONARY)) {
  const entry = LESSON_DICTIONARY[key];
  if (!entry) continue;
  const term = entry.term || entry.wordFr || entry.word || key;
  register(term, entry.definitionPt || '', entry.difficultyLevel);
}

/** Total unique words currently available in the bank (deduplicated by lemma). */
export function getUniqueWordCount(): number {
  return WORD_BANK.size;
}

/** All unique bank entries (deduplicated by lemma), for coverage tooling. */
export function getWordBankEntries(): WordBankEntry[] {
  return Array.from(WORD_BANK.values());
}

/** Number of unique words per CEFR level. */
export function getWordCountByLevel(): Record<string, number> {
  const counts: Record<string, number> = { A1: 0, A2: 0, B1: 0, B2: 0, C1: 0, C2: 0 };
  for (const entry of WORD_BANK.values()) {
    counts[entry.level] = (counts[entry.level] || 0) + 1;
  }
  return counts;
}

/** Ordered level progression metadata. */
export function getLevelProgression(): Array<{ level: string; count: number }> {
  const counts = getWordCountByLevel();
  return LEVEL_ORDER.map((level) => ({ level, count: counts[level] || 0 }));
}

/** Progress toward the 15.400 target (0..1). */
export function getWordBankProgress(): number {
  return Math.min(1, getUniqueWordCount() / TARGET_TOTAL_WORDS);
}

/**
 * Quantas palavras cada nível CEFR já possui versus sua meta, e quantas
 * ainda faltam para "fechar" aquele nível. Dirige a expansão do banco:
 * sempre completamos o nível mais defasado primeiro.
 */
export function getLevelTargetProgress(): Array<{
  level: string;
  count: number;
  target: number;
  cumulativeTarget: number;
  missing: number;
}> {
  const counts = getWordCountByLevel();
  return CEFR_LEVELS.map((level) => {
    const count = counts[level] || 0;
    const target = CEFR_LEVEL_TARGETS[level];
    return {
      level,
      count,
      target,
      cumulativeTarget: CEFR_CUMULATIVE_TARGETS[level],
      missing: Math.max(0, target - count),
    };
  });
}

/**
 * Próximo nível a ser preenchido, respeitando a progressão pedagógica
 * (A1 → C2): sempre completamos o nível mais básico que ainda tem lacunas.
 */
export function getNextLevelToFill(): string {
  const progress = getLevelTargetProgress();
  const next = progress.find((p) => p.missing > 0);
  return next ? next.level : 'C2';
}

/** Total de palavras que ainda faltam para atingir 15.400. */
export function getWordsRemaining(): number {
  return Math.max(0, TARGET_TOTAL_WORDS - getUniqueWordCount());
}
